"""Export a trained (discretized) DLGN to synthesizable SystemVerilog,
plus a self-checking testbench and its test vectors.

Generated design (dlgn_top):
  x --> [input reg] --> layer 1 --> ... --> layer D --> popcount tree
        --> argmax --> [output reg] --> scores, class_out
  * pipeline=False: layers are pure combinational (latency = 2 cycles)
  * pipeline=True : a register after every layer (latency = D + 2)
  * the input and output registers are always there, so timing reports
    give a real reg-to-reg Fmax.
  * popcount is a balanced adder tree (depth log2(group size)), not a
    100-deep ripple chain, so it doesn't dominate the critical path.
  * argmax: strict '>' scan from class 0, so ties go to the lowest
    index, matching numpy/torch argmax.
"""
import math
import os
import numpy as np

from .gates import VERILOG_EXPR
from . import hard


def _popcount_tree(bits, prefix, lines):
    """Emit a balanced adder tree; returns (net_name, width)."""
    level = [(b, 1) for b in bits]
    depth = 0
    while len(level) > 1:
        nxt = []
        for i in range(0, len(level) - 1, 2):
            (na, wa), (nb, wb) = level[i], level[i + 1]
            w = max(wa, wb) + 1
            name = f"{prefix}_d{depth}_{i // 2}"
            lines.append(f"  logic [{w-1}:0] {name};")
            lines.append(f"  assign {name} = {w}'({na}) + {w}'({nb});")
            nxt.append((name, w))
        if len(level) % 2:
            nxt.append(level[-1])
        level, depth = nxt, depth + 1
    return level[0]


def emit_rtl(net, pipeline=False, module="dlgn_top"):
    IN, K = net["in_dim"], net["n_classes"]
    layers = net["layers"]
    D, W = len(layers), len(layers[0]["gates"])
    G = W // K
    SW = max(1, math.ceil(math.log2(G + 1)))
    CW = max(1, math.ceil(math.log2(K)))
    LAT = (D + 2) if pipeline else 2

    L = []
    L.append(f"// Auto-generated by dlgn/export_verilog.py. Do not edit by hand.")
    L.append(f"// in={IN} width={W} depth={D} classes={K} group={G} "
             f"pipeline={int(pipeline)} latency={LAT}")
    L.append(f"module {module} (")
    L.append("  input  logic clk,")
    L.append("  input  logic rst,")
    L.append("  input  logic in_valid,")
    L.append(f"  input  logic [{IN-1}:0] x,")
    L.append("  output logic out_valid,")
    L.append(f"  output logic [{CW-1}:0] class_out,")
    L.append(f"  output logic [{K*SW-1}:0] scores")
    L.append(");")
    L.append(f"  localparam int LATENCY = {LAT};")
    L.append("")
    L.append(f"  logic [{IN-1}:0] l0;")
    L.append("  always_ff @(posedge clk) l0 <= x;")
    prev = "l0"
    for d, lay in enumerate(layers, 1):
        L.append("")
        L.append(f"  // ---- layer {d} ----")
        comb = f"l{d}_c"
        L.append(f"  logic [{W-1}:0] {comb};")
        for j, (a, b, g) in enumerate(zip(lay["ia"], lay["ib"], lay["gates"])):
            expr = VERILOG_EXPR[g].format(a=f"{prev}[{a}]", b=f"{prev}[{b}]")
            L.append(f"  assign {comb}[{j}] = {expr};")
        L.append(f"  logic [{W-1}:0] l{d};")
        if pipeline:
            L.append(f"  always_ff @(posedge clk) l{d} <= {comb};")
        else:
            L.append(f"  assign l{d} = {comb};")
        prev = f"l{d}"

    L.append("")
    L.append("  // ---- popcount per class ----")
    L.append(f"  logic [{SW-1}:0] sc [{K}];")
    for k in range(K):
        bits = [f"{prev}[{k*G + j}]" for j in range(G)]
        name, w = _popcount_tree(bits, f"pc{k}", L)
        L.append(f"  assign sc[{k}] = {SW}'({name});")

    L.append("")
    L.append("  // ---- argmax (ties -> lowest index) ----")
    L.append(f"  logic [{CW-1}:0] best;")
    L.append(f"  logic [{SW-1}:0] best_sc;")
    L.append("  always_comb begin")
    L.append("    best = '0;")
    L.append("    best_sc = sc[0];")
    L.append(f"    for (int k = 1; k < {K}; k++) begin")
    L.append("      if (sc[k] > best_sc) begin")
    L.append(f"        best = {CW}'(k);")
    L.append("        best_sc = sc[k];")
    L.append("      end")
    L.append("    end")
    L.append("  end")
    L.append("")
    L.append(f"  logic [{K*SW-1}:0] sc_flat;")
    L.append("  always_comb begin")
    L.append(f"    for (int k = 0; k < {K}; k++) sc_flat[k*{SW} +: {SW}] = sc[k];")
    L.append("  end")
    L.append("")
    L.append("  always_ff @(posedge clk) begin")
    L.append("    class_out <= best;")
    L.append("    scores    <= sc_flat;")
    L.append("  end")
    L.append("")
    L.append("  // valid travels alongside the data")
    L.append(f"  logic [{LAT-1}:0] vpipe;")
    L.append("  always_ff @(posedge clk) begin")
    L.append("    if (rst) vpipe <= '0;")
    if LAT > 1:
        L.append(f"    else     vpipe <= {{vpipe[{LAT-2}:0], in_valid}};")
    else:
        L.append("    else     vpipe <= in_valid;")
    L.append("  end")
    L.append(f"  assign out_valid = vpipe[{LAT-1}];")
    L.append("endmodule")
    return "\n".join(L) + "\n", dict(IN=IN, K=K, SW=SW, CW=CW, LAT=LAT,
                                      W=W, D=D, G=G)


def emit_tb(p, n_vec, module="dlgn_top"):
    IN, K, SW, CW = p["IN"], p["K"], p["SW"], p["CW"]
    return f"""// Auto-generated self-checking testbench. Streams one vector per clock
// (back-to-back, like real inference) and compares every class score and
// the predicted class against the Python golden model, bit for bit.
`timescale 1ns/1ps
module tb_dlgn;
  localparam int IN = {IN}, K = {K}, SW = {SW}, CW = {CW}, N = {n_vec};
  logic clk = 0, rst = 1, in_valid = 0;
  logic [IN-1:0] x = '0;
  logic out_valid;
  logic [CW-1:0] class_out;
  logic [K*SW-1:0] scores;

  logic [IN-1:0]   xmem [N];
  logic [K*SW-1:0] smem [N];
  logic [CW-1:0]   cmem [N];

  {module} dut (.clk, .rst, .in_valid, .x, .out_valid, .class_out, .scores);

  always #5 clk = ~clk;   // 100 MHz nominal; RTL sim is cycle-accurate only

  int nout = 0, nerr = 0, cyc = 0;

  initial begin
    $readmemh("x.hex", xmem);
    $readmemh("exp_scores.hex", smem);
    $readmemh("exp_class.hex", cmem);
`ifdef DUMP
    $dumpfile("dlgn.vcd");
    $dumpvars(0, dut);
`endif
    repeat (3) @(posedge clk);
    rst <= 0;
    for (int i = 0; i < N; i++) begin
      @(posedge clk);
      in_valid <= 1;
      x <= xmem[i];
    end
    @(posedge clk);
    in_valid <= 0;
    wait (nout == N);
    @(posedge clk);
    if (nerr == 0) $display("PASS: %0d/%0d vectors bit-exact (scores + class)", nout, N);
    else           $display("FAIL: %0d mismatches out of %0d", nerr, N);
    $finish;
  end

  always @(posedge clk) begin
    cyc <= cyc + 1;
    if (cyc > N + 1000) begin
      $display("FAIL: timeout, got %0d/%0d outputs", nout, N);
      $finish;
    end
    if (!rst && out_valid) begin
      if (scores !== smem[nout] || class_out !== cmem[nout]) begin
        nerr++;
        if (nerr <= 10)
          $display("MISMATCH vec %0d: class %0d (exp %0d) scores %h (exp %h)",
                   nout, class_out, cmem[nout], scores, smem[nout]);
      end
      nout++;
    end
  end
endmodule
"""


def write_vectors(net, x_bits, outdir, p):
    IN, K, SW = p["IN"], p["K"], p["SW"]
    sc = hard.scores(net, x_bits)
    cl = sc.argmax(1)
    hx = math.ceil(IN / 4)
    hs = math.ceil(K * SW / 4)
    with open(os.path.join(outdir, "x.hex"), "w") as f:
        for row in np.asarray(x_bits, dtype=bool):
            v = 0
            for j in np.flatnonzero(row):
                v |= 1 << int(j)
            f.write(f"{v:0{hx}x}\n")
    with open(os.path.join(outdir, "exp_scores.hex"), "w") as f:
        for row in sc:
            v = 0
            for k, s in enumerate(row):
                v |= int(s) << (k * SW)
            f.write(f"{v:0{hs}x}\n")
    with open(os.path.join(outdir, "exp_class.hex"), "w") as f:
        for c in cl:
            f.write(f"{int(c):x}\n")
    return sc, cl


def export(net, x_bits, outdir, pipeline=False):
    os.makedirs(outdir, exist_ok=True)
    rtl, p = emit_rtl(net, pipeline=pipeline)
    with open(os.path.join(outdir, "dlgn_top.sv"), "w") as f:
        f.write(rtl)
    with open(os.path.join(outdir, "tb_dlgn.sv"), "w") as f:
        f.write(emit_tb(p, len(x_bits)))
    write_vectors(net, x_bits, outdir, p)
    return p
